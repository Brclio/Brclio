import {build} from 'esbuild';
import {copyFile, mkdir} from 'node:fs/promises';

// Ship executable migration helpers with the portable Skill. The ESM launcher
// bundles its GitHub App provider, so copying the Skill needs no npm install.
const scripts = new URL('../../docs/shared-user-data/skills/brclio-user-data/scripts/', import.meta.url);
await mkdir(scripts, {recursive: true});
await copyFile(new URL('./migrate-user-data.py', import.meta.url), new URL('migrate-user-data.py', scripts));
await build({
  entryPoints: [new URL('./migrate-with-github-app.mjs', import.meta.url).pathname],
  outfile: new URL('migrate-with-github-app.mjs', scripts).pathname,
  bundle: true, platform: 'node', format: 'esm', target: 'node20',
  banner: {js: '// Generated by cloudflare/scripts/package-data-skill.mjs; no credentials included.'}
});
console.log(JSON.stringify({portableSkillMigrationHelpers: true, dependencies: 'Node.js 20+, Python 3, Git'}));
